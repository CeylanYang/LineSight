"""Import the approved HTML's exact logo/particle coordinates, without glints."""
import base64
import hashlib
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = Path(r'C:\Users\29668\Downloads\LineSight_粒子聚合与触觉动效预览_v4_2.html')
html = source.read_text(encoding='utf-8')
particles = json.loads(re.search(r'const PARTICLES=(\[.*?\]);', html).group(1))
logo = base64.b64decode(re.search(r'const LOGO_SRC="data:image/png;base64,([^"]+)"', html).group(1))
assets = root / 'assets/brand'
assets.mkdir(parents=True, exist_ok=True)
(assets / 'reveal_logo.png').write_bytes(logo)
rows = [
    '// Generated by tool/import_brand_reveal.py from the approved V4.2 preview.',
    '// dart format off',
    '// Fields: group, x, y, startX, startY, angle, radius, delay, size, seed, blue.',
    'const brandParticles = <(String, double, double, double, double, double, double, double, double, double, bool)>[',
]
for p in sorted(particles, key=lambda item: item['g']):
    nums = ', '.join(str(float(p[k])) for k in ('x', 'y', 'sx', 'sy', 'a', 'r', 'd', 'size', 'seed'))
    rows.append(f"  ('{p['g']}', {nums}, {str(p['tone'] == 'blue').lower()}),")
rows.append('];\n')
(root / 'lib/brand_particles.dart').write_text('\n'.join(rows), encoding='utf-8')
print(json.dumps({'particles': len(particles), 'logoBytes': len(logo), 'sourceSha256': hashlib.sha256(source.read_bytes()).hexdigest()}, indent=2))
