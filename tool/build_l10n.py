import json
from pathlib import Path

source = json.loads(Path('tool/l10n_source.json').read_text(encoding='utf-8'))
english = {}
for line in Path('tool/en_translations.txt').read_text(encoding='utf-8').splitlines():
    key, value = line.split('|', 1)
    if key in english:
        raise ValueError(f'Duplicate translation {key}')
    english[key] = value.replace('\\n', '\n')
assert source.keys() == english.keys(), (source.keys() - english.keys(), english.keys() - source.keys())
import re
for key in source:
    assert sorted(re.findall(r'\{\d+\}', source[key])) == sorted(re.findall(r'\{\d+\}', english[key])), key
def dart(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')
Path('lib/l10n_catalog.dart').write_text('// Generated by tool/build_l10n.py. Edit tool/en_translations.txt.\nconst englishMessages = <String, String>{\n' + ''.join(f'  {dart(source[k])}: {dart(english[k])},\n' for k in source) + '};\n', encoding='utf-8')
print(f'{len(source)} bilingual messages, placeholders complete')
